/**
 * The marketplace, with nobody's wallet attached.
 *
 * Arsalan asked for demo data "if someone doesn't want to securely connect",
 * and that is the right call: most people who open a portfolio piece will not
 * install a browser extension to look at it. So the whole marketplace runs on
 * invented state, in memory, and every button does what it would really do.
 *
 * Two rules this file exists to keep:
 *
 * 1. **It must never be mistakable for the chain.** Every screen carries a
 *    demo badge, the wallet address is obviously fake, and nothing here ever
 *    touches `window.ethereum`.
 * 2. **It must behave like the contract, including when it refuses.** Buying
 *    your own listing fails here for the same reason it fails on chain. A demo
 *    that only shows the happy path teaches the visitor something untrue.
 *
 * Artwork comes from `demo-art.js`, which is generated by the contract itself,
 * so the pictures are real even though the ledger is not.
 */

import { DEMO_ART } from "./demo-art.js";

/** A wallet address that could not possibly be anybody's. */
export const DEMO_ADDRESS = "0xDEM00000000000000000000000000000000DEM0";

const FEE_BPS = 250n;

/** Invented sellers, so the market does not look like one person talking to themselves. */
const SELLERS = [
  "0xA11CE0000000000000000000000000000000A11C",
  "0xB0B0000000000000000000000000000000000B0B",
  "0xCAR0L000000000000000000000000000000CAR01",
];

const ether = (n) => BigInt(Math.round(n * 1000)) * 10n ** 15n;

/** Prices that look like a real market rather than a price list. */
const PRICES = [0.4, 1.2, 0.85, 2.5, 0.6, 3.1, 0.95, 1.75, 0.5, 4.2, 1.1, 0.7];

export function createDemo() {
  const tokens = DEMO_ART.map((art, i) => ({
    id: BigInt(art.id),
    svg: art.svg,
    royalty: art.royalty,
    // The first three belong to the visitor, so "your items" is not empty and
    // listing something is the first thing they can try.
    owner: i < 3 ? DEMO_ADDRESS : SELLERS[i % SELLERS.length],
    listed: i >= 3 && i < 10,
    price: ether(PRICES[i] ?? 1),
  }));

  return {
    isDemo: true,
    address: DEMO_ADDRESS,
    balance: ether(12.4),
    proceeds: 0n,
    feeBps: Number(FEE_BPS),
    tokens,

    listings() {
      return this.tokens.filter((t) => t.listed);
    },

    mine() {
      return this.tokens.filter((t) => t.owner === DEMO_ADDRESS);
    },

    find(id) {
      return this.tokens.find((t) => t.id === BigInt(id));
    },

    /** The split, worked out the way the contract works it out. */
    quote(token) {
      const royalty = (token.price * BigInt(Math.round(parseFloat(token.royalty) * 100))) / 10_000n;
      const fee = (token.price * FEE_BPS) / 10_000n;
      return { royalty, fee, toSeller: token.price - royalty - fee };
    },

    mint() {
      // The gallery is fixed at twelve, so a mint hands back one the visitor
      // does not already own rather than inventing a thirteenth picture that
      // no contract would ever draw.
      const spare = this.tokens.find((t) => t.owner !== DEMO_ADDRESS && !t.listed);
      if (!spare) throw new Error("demo-sold-out");

      spare.owner = DEMO_ADDRESS;
      return spare;
    },

    list(id, price) {
      const token = this.find(id);
      if (!token) throw new Error("NotListed");
      if (token.owner !== DEMO_ADDRESS) throw new Error("NotOwner");
      if (price <= 0n) throw new Error("PriceIsZero");

      token.listed = true;
      token.price = price;
      return token;
    },

    cancel(id) {
      const token = this.find(id);
      if (!token || !token.listed) throw new Error("NotListed");
      if (token.owner !== DEMO_ADDRESS) throw new Error("NotSeller");

      token.listed = false;
      return token;
    },

    buy(id) {
      const token = this.find(id);
      if (!token || !token.listed) throw new Error("NotListed");

      // The contract refuses this too. A demo that lets you buy your own
      // listing is teaching the visitor something that is not true.
      if (token.owner === DEMO_ADDRESS) throw new Error("own-listing");
      if (this.balance < token.price) throw new Error("WrongPayment");

      this.balance -= token.price;
      token.owner = DEMO_ADDRESS;
      token.listed = false;
      return token;
    },

    /** Credit the visitor as though one of their listings had sold. */
    sellOne() {
      const sold = this.tokens.find((t) => t.owner === DEMO_ADDRESS && t.listed);
      if (!sold) return null;

      const { toSeller } = this.quote(sold);
      this.proceeds += toSeller;
      sold.owner = SELLERS[0];
      sold.listed = false;
      return sold;
    },

    withdraw() {
      if (this.proceeds === 0n) throw new Error("NothingToWithdraw");

      const amount = this.proceeds;
      this.balance += amount;
      this.proceeds = 0n;
      return amount;
    },
  };
}
